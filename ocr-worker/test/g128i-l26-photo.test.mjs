/* plane G128i L26 (fix round 9; X29; corpus R set, K4426 "Still MISSING" row 6): PHOTO OCR READ 59 OF 234 WORDS WITH NO NOTE. The walk's photographed page came back as 25 percent of its words and the member never said so.
   The statement its truth names (ocr-worker R24, R25): a picture is read through the member's REAL path (the committed engine, the real picture renderer, the member's own handler), and what the member says of it is TRUE and
   NEVER SILENT: the share of the page's words it states (`legibility.share`) is within a tenth of the share truly read and never over it; a share under LEGIBLE_NOTE_BELOW (0.8) is said in a note; a share under
   LEGIBLE_REFUSE_BELOW (0.2) is refused PICTURE_NOT_LEGIBLE with its figures and no text returned. The photographs: the walk's own (`ocr-worker/test/fixtures/page-*.jpg`, truth `page-words.json`: `page-hard` is 231 words at 110 dpi, tilted
   2.4 degrees, with perspective and noise, L26's page) and a family generated by `imggen` (a tilt, shade and noise, 110 dpi, 18 lines) whose truth is its lines. Accuracy is not judged here (that is the member's own R24 floor); the STATEMENT is. */
