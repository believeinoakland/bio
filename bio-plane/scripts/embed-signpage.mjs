/* Embeds the signing page into the plane, so a group's own instance can hand
 * it to them instead of telling them to go find a file.
 *
 * The page is still exactly one self-contained file with no network calls of
 * any kind; serving it changes where the bytes come from, not what they do.
 * That matters for a group of ordinary people: "click this link" is a thing
 * anyone can follow, and "download this HTML file and open it from your
 * downloads folder" is not.
 *
 * JSON.stringify does the escaping, so the page can contain backticks,
 * dollar-braces, and backslashes without the embedding corrupting it. The
 * 0.3.8 defect was exactly that kind of corruption, and it is not repeatable
 * through this path.
 *
 * Run from bio-plane/: `npm run embed:sign`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../tools/sign-release.html");
const out = path.resolve(here, "../src/signpage.mjs");

const html = readFileSync(src, "utf8");
if (!/id="gen"/.test(html)) throw new Error("signing page does not look right: no generate button found");
if (/\b(fetch|XMLHttpRequest|sendBeacon|WebSocket)\s*\(/.test(html))
  throw new Error("signing page contains an outbound call; refusing to embed it");

writeFileSync(out,
  "/* GENERATED by scripts/embed-signpage.mjs from tools/sign-release.html. Do not edit. */\n"
  + `export const SIGN_HTML = ${JSON.stringify(html)};\n`);
console.log(`embedded the signing page, ${html.length} chars, into src/signpage.mjs`);
