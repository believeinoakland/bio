/* Embeds the signing page into the plane, so a group's own instance can hand
 * it to them instead of telling them to go find a file.
 *
 * The page is still exactly one self-contained file with no network calls of
 * any kind; serving it changes where the bytes come from, not what they do.
 * That matters for a group of ordinary people: "click this link" is a thing
 * anyone can follow, and "download this HTML file and open it from your
 * downloads folder" is not.
 *
 * JSON.stringify does the escaping, so the page can contain backticks,
 * dollar-braces, and backslashes without the embedding corrupting it. The
 * 0.3.8 defect was exactly that kind of corruption, and it is not repeatable
 * through this path.
 *
 * Run from bio-plane/: `npm run embed:sign`. The page's source is
 * `src/sign-release.html`, owned with this script and `src/signpage.mjs` by
 * the `signatures` module (K33), whose own tests check the committed render.
 *
 * `renderSignpage` is EXPORTED (FL-10) so the fleet-bundle gate can assert the
 * committed src/signpage.mjs IS the deterministic render of the page WITHOUT
 * writing anything — verification never writes. One expression of the render
 * lives here; the gate imports it rather than restating the header string,
 * which is how the two would drift.
 *
 * THE PAGE'S ID PATTERN IS REGENERATED HERE, never edited by hand (R42; S0-13,
 * K1470). The page checks a notice's or case's id with its own copy of the
 * pattern the plane's `noticeStatement` and `docketStatement` use, and that
 * pattern's counter is `record-grammar`'s. `syncIdPattern` writes the plane's
 * `OPAQUE_ID_RE` (derived from `record-grammar` in `src/sshsig.mjs`) over the
 * page's `const OPAQUE_ID_RE = /…/;` line; `main` saves the page when that
 * changed it, then renders. The module's tests require the committed page to be
 * a fixed point of `syncIdPattern`, so a hand edit or a stale copy is red.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import { OPAQUE_ID_RE } from "../src/sshsig.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
export const SIGNPAGE_SRC = path.resolve(here, "../src/sign-release.html");
export const SIGNPAGE_OUT = path.resolve(here, "../src/signpage.mjs");

/** The whole render, deterministic: same html in, same module source out. */
export function renderSignpage(html) {
  if (!/id="gen"/.test(html)) throw new Error("signing page does not look right: no generate button found");
  if (/\b(fetch|XMLHttpRequest|sendBeacon|WebSocket)\s*\(/.test(html))
    throw new Error("signing page contains an outbound call; refusing to embed it");
  return "/* GENERATED by scripts/embed-signpage.mjs from src/sign-release.html. Do not edit. */\n"
    + `export const SIGN_HTML = ${JSON.stringify(html)};\n`;
}

const ID_LINE = /^const OPAQUE_ID_RE = \/.*\/;$/m;

/** The page with its id pattern's copy replaced by the plane's (R42). */
export function syncIdPattern(html) {
  const lines = html.match(new RegExp(ID_LINE.source, "gm")) || [];
  if (lines.length !== 1) throw new Error(`signing page does not look right: ${lines.length} OPAQUE_ID_RE lines, expected 1`);
  return html.replace(ID_LINE, () => `const OPAQUE_ID_RE = ${OPAQUE_ID_RE};`);
}

function main() {
  const was = readFileSync(SIGNPAGE_SRC, "utf8");
  const html = syncIdPattern(was);
  if (html !== was) {
    writeFileSync(SIGNPAGE_SRC, html);
    console.log(`regenerated the page's id pattern from record-grammar: ${OPAQUE_ID_RE}`);
  }
  writeFileSync(SIGNPAGE_OUT, renderSignpage(html));
  console.log(`embedded the signing page, ${html.length} chars, into src/signpage.mjs`);
}

/* Importable for the gate without writing. */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
