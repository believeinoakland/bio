/* wizard-scripts: writes the carried data from the design stream's files (R13, R22, R41, R42, R45; DEC-139 (5), DEC-148, DEC-266).
 *
 *   node bio-plane/src/wizard-scripts/build-data.mjs                     write the three files beside this one
 *   node bio-plane/src/wizard-scripts/build-data.mjs --check             exit 1, naming the first difference, when a carried
 *                                                                        file is not what its sources would generate
 *   --from <dir>  the directory of the vendored design files (default: the module's tests' `source/`, where each file
 *                 stands as it does at its commit: `registry.json` and `library-<commit>.json`)
 *   --out <dir>   where the generated files are written or checked (default: beside this file; the tests' fixtures)
 *
 * The sources are `SOURCES`, below, each at its own commit: the registry at the design commit the job's START names
 * (R41, R45; `7be06eb4cb` at T50, the design branch's last merge into `tranche/T50`, K3750; `958d998ccb`, then `1cc4a957f0` in T51's fix round, K4196, K4197, `aa8bdcd0b4` at FR-49, K4204, and `0310c4953d` in T51's fix round 2, K4311, and `654a735535` at DEC-396, R48; `43379a1a44` at DEC-402, R49, and `f72b2f8a4c` at DEC-419, R50); the library's version 1 kept at
 * `d129238bf3` (DEC-148's, R22, K1790); with the newer libraries, the versions BOB adopts from each (`LIBRARY_ADOPTED`)
 * and the scripts he adds (`LIBRARY_ADDED`), K2241, R30, R32, R36, and the whole library re-taken from the file at the
 * design commit (`LIBRARY_RETAKEN`, R42); the front doors from the library at `DOORS_SOURCE` (R33, R41). It writes
 * `screen-registry.mjs`, `civicsmith-library.mjs` and `front-doors.mjs`, each naming its own source's commit, path and
 * SHA-256. A run on the same files writes the same bytes. Not part of the bundle: nothing imports it, and importing it (as
 * a test that reads every module file does) writes nothing: it runs only as a command. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { sha256HexSync } from "../record-grammar/sha256.mjs";
import { screensFromFile, libraryFromFile, adoptedLibrary, doorsFromFile, DOORS_SOURCE, ELSEWHERE, ELSEWHERE_FROZEN } from "./data.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const lines = (list) => `[\n${list.map((x) => `  ${JSON.stringify(x)},`).join("\n")}\n]`;

/** R41, R42: the files the carried data is generated from, each by its commit and the name it has in `--from`'s directory. */
export const SOURCES = Object.freeze({
  registry: Object.freeze({ commit: "c752a602da", file: "registry.json" }),
  library: Object.freeze({ commit: "d129238bf3", file: "library.json" }),
  newer: Object.freeze(["e08cd35ecb", "3660c18803", "3f40899950", "a0fab7abf0", "f90b187c7b", "4664e8efd4", "7be06eb4cb", "20c8001300", "2a64c5ae77", "1cc4a957f0"]
    .map((commit) => Object.freeze({ commit, file: `library-${commit}.json` }))),
});
/** The generated files, by name. */
export const GENERATED = Object.freeze(["screen-registry.mjs", "civicsmith-library.mjs", "front-doors.mjs"]);

const REGISTRY_HEAD = `/* GENERATED by build-data.mjs from the design stream's screen registry (wizard-scripts R13; DEC-139 (5);
 * K1565): every screen with its id, name and purpose, its declared and function acts as ops in the file's order, and
 * its owed acts apart, each with the number of acts before it. Do not edit: run build-data.mjs. */
import { deepFreeze } from "./data.mjs";
`;
const LIBRARY_HEAD = `/* GENERATED by build-data.mjs from the design stream's Civicsmith library (wizard-scripts R1, R13, R14, R22, R42; DEC-121
 * (1), (9); DEC-148, Bob's "S2: approved", 2026-10-06; K1784, K1785, K1790; R30, DEC-194 (5); DEC-266, DEC-279, DEC-281): the scripts shipped
 * with the release, read-only to every group, each version authored by the Civicsmith library; three required.
 * \`plane\` passes it to \`wizardRegister\` at start (a call without \`library\` registers it); the release suite runs
 * \`requiredFailures\` over it. A later version, or a new script, is carried only as BOB adopts it (K2241). Do not edit:
 * run build-data.mjs.
 *
 * An entry: \`{id, name, start, origin, scope, required, version, steps, author, approved: {by, at, ruling?}, source,
 * earlier?}\`: \`source\` the commit its steps come from; \`earlier\` each earlier version, \`[{version, steps, author,
 * approved, source}]\`, when BOB has adopted a newer one (R22; K2241). */
import { deepFreeze } from "./data.mjs";
`;

const DOORS_HEAD = `/* GENERATED by build-data.mjs from the design stream's Civicsmith library (wizard-scripts R23, R33, R37; DEC-129 (7),
 * DEC-198 (4); N992): the home's front doors ("What brought you here?"), each \`{door, scripts}\` naming the file's script
 * ids in its order; \`startFrom\` answers a door with only the scripts offered to the viewer, and leaves out a door with
 * none; the sixth door, \`ELSEWHERE_DOOR\`, is always answered after them (R37). The doors' words are \`words.json\`'s \`door.front.*\`, read by the interface, not here. Do not edit: run
 * build-data.mjs. */
import { deepFreeze } from "./data.mjs";
`;

/* The text of each generated file, from the files of `dir` that SOURCES names. */
export function generate(dir) {
  const read = (x) => readFileSync(join(dir, x.file), "utf8");
  const source = (x, text) => ({ commit: x.commit, path: `docs/development/ux-substrate/screens/${x.file.startsWith("registry") ? "registry.json" : "library.json"}`, sha256: sha256HexSync(text) });
  const regText = read(SOURCES.registry);
  const libText = read(SOURCES.library);
  const screens = screensFromFile(JSON.parse(regText));
  const newer = SOURCES.newer.map((x) => ({ ...x, text: read(x) }));
  const library = adoptedLibrary(JSON.parse(libText), SOURCES.library.commit, newer.map((n) => ({ file: JSON.parse(n.text), commit: n.commit })));
  const out = {};
  out["screen-registry.mjs"] = `${REGISTRY_HEAD}
export const SCREEN_REGISTRY_SOURCE = deepFreeze(${JSON.stringify(source(SOURCES.registry, regText))});

export const SCREEN_REGISTRY = deepFreeze(${lines(screens)});
`;
  out["civicsmith-library.mjs"] = `${LIBRARY_HEAD}
export const CIVICSMITH_LIBRARY_SOURCE = deepFreeze(${JSON.stringify(source(SOURCES.library, libText))});

/** R22, R30, R42 (K2241): the newer libraries BOB's adopted versions and added scripts come from, and the one the whole library is re-taken from, each at its own commit (\`LIBRARY_ADOPTED\`, \`LIBRARY_ADDED\`, \`LIBRARY_RETAKEN\`). */
export const CIVICSMITH_LIBRARY_ADOPTED_SOURCES = deepFreeze(${lines(newer.map((n) => source(n, n.text)))});

export const CIVICSMITH_LIBRARY = deepFreeze(${lines(library)});
`;
  const doorsFile = newer.find((n) => n.commit === DOORS_SOURCE);
  if (!doorsFile) throw new Error(`the front doors come from the library at ${DOORS_SOURCE}, which is not given`);
  const all = doorsFromFile(JSON.parse(doorsFile.text));
  const doors = all.filter((d) => d.door !== ELSEWHERE);
  /* R37, R41: the sixth door, the file's when it holds one (normalised: it names no script), else DEC-227 (1)'s frozen data */
  const sixth = JSON.parse(doorsFile.text).doors.find((d) => d.door === ELSEWHERE);
  const elsewhere = sixth ? { door: sixth.door, scripts: [], opens: sixth.opens ?? sixth.door } : { ...ELSEWHERE_FROZEN, scripts: [] };
  out["front-doors.mjs"] = `${DOORS_HEAD}
export const FRONT_DOORS_SOURCE = deepFreeze(${JSON.stringify(source(doorsFile, doorsFile.text))});

export const FRONT_DOORS = deepFreeze(${lines(doors)});

/** R37, R41: the sixth door, always answered after these (${sixth ? "the file's own" : "DEC-227 (1)'s frozen data: the library holds none at this commit"}). */
export const ELSEWHERE_DOOR = deepFreeze(${JSON.stringify(elsewhere)});
`;
  return { files: out, summary: `${doors.length} front doors and the sixth from ${DOORS_SOURCE}; ${screens.length} screens and ${library.length} scripts `
    + `(registry ${SOURCES.registry.commit}, library ${SOURCES.library.commit}, re-taken from ${SOURCES.newer.at(-1).commit}: `
    + `${library.filter((e) => e.source === SOURCES.newer.at(-1).commit).length} scripts at the file's content)` };
}

/** The first difference between a carried file and what its sources generate: the first line that differs, or null. */
export function firstDifference(have, want) {
  if (have === want) return null;
  const a = have.split("\n"), b = want.split("\n");
  for (let i = 0; i < Math.max(a.length, b.length); i++)
    if (a[i] !== b[i]) return `line ${i + 1}: have ${JSON.stringify((a[i] ?? null) && a[i].slice(0, 160))}, the sources give ${JSON.stringify((b[i] ?? null) && b[i].slice(0, 160))}`;
  return "differs";
}

function main(argv) {
  const opt = (name, dflt) => { const i = argv.indexOf(name); return i >= 0 && argv[i + 1] ? argv[i + 1] : dflt; };
  const from = opt("--from", join(here, "../../test/m/wizard-scripts/source"));
  const out = opt("--out", here);
  let made;
  try { made = generate(from); } catch (e) { console.error(`wizard-scripts build-data: ${e.message}`); return 1; }
  if (argv.includes("--check")) {
    let stale = 0;
    for (const name of GENERATED) {
      let have = null;
      try { have = readFileSync(join(out, name), "utf8"); } catch { /* absent */ }
      const d = have === null ? "the generated file is absent" : firstDifference(have, made.files[name]);
      if (d) { console.error(`wizard-scripts: ${join(out, name)} is stale: ${d}`); stale++; }
    }
    if (stale) return 1;
    console.log("wizard-scripts: screen-registry.mjs, civicsmith-library.mjs and front-doors.mjs match their sources");
    return 0;
  }
  for (const name of GENERATED) writeFileSync(join(out, name), made.files[name]);
  console.log(`wrote ${made.summary}`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) process.exitCode = main(process.argv.slice(2));
